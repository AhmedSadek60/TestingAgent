class Unavailable(Exception):
    """A category has nothing to give, with the reason that is shown to the person."""


def _aware(moment: datetime | None) -> datetime | None:
    if moment is None:
        return None
    return moment if moment.tzinfo else moment.replace(tzinfo=UTC)


def _iso(moment: datetime | None) -> str | None:
    found = _aware(moment)
    return found.isoformat() if found else None


@dataclass
class Gathered:
    """One piece of masked text, before it is kept."""

    category: str
    path: str
    source: str
    media_type: str
    result: DiagnosticResult | None = None
    outcome: str = "collected"
    detail: str = ""
    time_from: datetime | None = None
    time_to: datetime | None = None
    truncated: bool = False
    raw_size: int = 0
    data: bytes = b""


@dataclass
class Context:
    actor: Actor
    request: DiagnosticsRequest
    start: datetime
    end: datetime
    is_operator: bool
    notes: list[str] = field(default_factory=list)


class DiagnosticsService:
    def __init__(
        self,
        submissions: SubmissionService,
        store: Store,
        artifacts: ArtifactStore,
        config: AgentLabConfig,
        redactor: DiagnosticRedactor,
        *,
        clock: Callable[[], datetime] = utcnow,
    ) -> None:
        self.submissions = submissions
        self.db = submissions.db
        self.store = store
        self.artifacts = artifacts
        self.app = config  # the whole configuration: the environment says what is switched on
        self.config = config.feedback
        self.redactor = redactor
        self._now = clock

    # ================================================================================================ the menu
    def available(
        self, actor: Actor, *, run_id: str | None = None, test_id: str | None = None, trace_id: str | None = None
    ) -> DiagnosticsAvailable:
        cfg = self.config.diagnostics
        sources = []
        for category in CATEGORIES:
            label, description = LABELS[category]
            available, manual, reason, needs = self._availability(category, actor, run_id, test_id, trace_id)
            sources.append(
                DiagnosticSource(
                    id=category,
                    label=label,
                    description=description,
                    available=available,
                    manual=manual,
                    reason=reason,
                    needs=needs,
                )
            )
        return DiagnosticsAvailable(
            sources=sources,
            windows=["last_5_minutes", "last_15_minutes", "last_30_minutes", "custom"],
            max_window_minutes=cfg.max_window_minutes,
            consent_text=CONSENT_TEXT,
            limits={
                "max_item_kb": cfg.max_item_kb,
                "max_browser_entries": cfg.max_browser_entries,
                "draft_hours": cfg.draft_hours,
                "max_collections_per_hour": cfg.max_collections_per_hour,
            },
        )

    def _availability(
        self, category: str, actor: Actor, run_id: str | None, test_id: str | None, trace_id: str | None
    ) -> tuple[bool, bool, str | None, list[str]]:
        """(available, manual, reason, what it needs)."""
        cfg = self.config.diagnostics
        staff_only = "Evaluation data is available to maintainers only."
        if category == "environment":
            return True, False, None, []
        if category in ("application_logs", "backend_logs"):
            if not cfg.capture_logs:
                return (
                    False,
                    False,
                    "Log capture is switched off on this server (feedback.diagnostics.capture_logs).",
                    [],
                )
            if category == "backend_logs" and not self._has_lines("worker"):
                return False, False, "No background worker has logged anything that is kept yet.", []
            return True, False, None, []
        if category == "errors":
            return True, False, None, []
        if category == "browser":
            return True, False, "The web interface sends these itself; a program calling the API has none.", []
        if category == "screenshot":
            return (
                False,
                True,
                "AgentLab cannot capture a screenshot of your page. Attach one as a file to your report.",
                [],
            )
        if not actor.is_staff:
            return False, False, staff_only, []
        if category == "run_metadata":
            if not run_id:
                return False, False, "Say which run it concerns.", ["run_id"]
            return True, False, None, ["run_id"]
        if category == "test_summary":
            if not (run_id and test_id):
                return False, False, "Say which run and which test it concerns.", ["run_id", "test_id"]
            return True, False, None, ["run_id", "test_id"]
        if category == "trace":
            if not run_id or not (test_id or trace_id):
                return False, False, "Say which run, and which test or trace, it concerns.", ["run_id", "test_id"]
            return True, False, None, ["run_id", "test_id"]
        return False, False, "Unknown category.", []

    def _has_lines(self, process: str) -> bool:
        L = orm.LogEventRow
        with self.db.session() as s:
            return s.scalar(select(L.id).where(L.process == process).limit(1)) is not None

    # ============================================================================================== collecting
    def preview(self, actor: Actor, request: DiagnosticsRequest) -> DiagnosticCollectionOut:
        """Collect and mask, show the result, keep nothing."""
        gathered, context = self._gather(actor, request)
        return self._present(None, "preview", gathered, context, items=None)

    def collect(self, actor: Actor, request: DiagnosticsRequest, *, client: str = "") -> DiagnosticCollectionOut:
        """Collect and mask, and keep the masked result as a draft until it is attached or expires."""
        self._expire()
        self._check_allowance(actor)
        gathered, context = self._gather(actor, request)
        now = self._now()
        cfg = self.config.diagnostics
        kept: list[tuple[Gathered, str | None]] = []
        for item in gathered:
            artifact = None
            if item.outcome == "collected" and item.data:
                artifact = self.artifacts.put(
                    item.data,
                    kind=KIND,
                    media_type=item.media_type,
                    name=item.path,
                    sensitivity="restricted",
                    redact=False,
                    meta={"category": item.category},
                ).id
            kept.append((item, artifact))
        with self.db.session() as s:
            row = orm.DiagnosticCollectionRow(
                owner_user_id=actor.user_id,
                owner_label=actor.stored_label[:80],
                requested=request.model_dump(mode="json", exclude={"browser"}),
                window_from=context.start,
                window_to=context.end,
                expires_at=now + timedelta(hours=cfg.draft_hours),
                created_at=now,
                status="draft",
            )
            s.add(row)
            s.flush()
            rows: list[orm.DiagnosticItemRow] = []
            for item, artifact in kept:
                report = item.result.report() if item.result else {}
                rows.append(
                    orm.DiagnosticItemRow(
                        collection_id=row.id,
                        category=item.category,
                        path=item.path,
                        source=item.source[:120],
                        media_type=item.media_type,
                        time_from=item.time_from,
                        time_to=item.time_to,
                        outcome=item.outcome,
                        detail=item.detail[:300],
                        artifact_id=artifact,
                        size=len(item.data),
                        truncated=item.truncated,
                        included=item.outcome == "collected",
                        redaction_status=item.result.status if item.result else "clean",
                        redaction_report=report,
                        created_at=now,
                        status="active",
                    )
                )
            s.add_all(rows)
            s.flush()
            self.submissions.audit(
                s,
                "diagnostics_collected",
                actor,
                None,
                client=client,
                collection=row.id,
                categories=sorted({i.category for i in gathered}),
                collected=sum(1 for i in gathered if i.outcome == "collected"),
            )
            return self._present(row, "draft", gathered, context, items=rows)

    def _check_allowance(self, actor: Actor) -> None:
        """Collecting reads logs and masks text: a person may do it a limited number of times an hour."""
        cfg = self.config.diagnostics
        C = orm.DiagnosticCollectionRow
        now = self._now()
        with self.db.session() as s:
            made = [
                _aware(t)
                for t in s.scalars(
                    select(C.created_at)
                    .where(
                        C.owner_user_id == actor.user_id if actor.user_id else C.owner_label == actor.label,
                        C.created_at >= now - HOUR,
                    )
                    .order_by(C.created_at)
                )
            ]
        if len(made) >= cfg.max_collections_per_hour:
            wait = max(60, int((made[0] + HOUR - now).total_seconds())) if made[0] else 600
            raise QuotaExceeded(
                f"you have collected diagnostics {len(made)} times in the last hour, which is the most this server "
                "allows; try again later",
                retry_after_seconds=wait,
            )

    def _expire(self) -> None:
        """Delete drafts nobody attached: what was collected for a report that was never made is not kept."""
        now = self._now()
        C, Itm = orm.DiagnosticCollectionRow, orm.DiagnosticItemRow
        with self.db.session() as s:
            stale = list(s.scalars(select(C).where(C.status == "draft", C.expires_at < now).limit(200)))
            artifacts = []
            for collection in stale:
                artifacts += [
                    a
                    for a in s.scalars(select(Itm.artifact_id).where(Itm.collection_id == collection.id))
                    if a is not None
                ]
                s.delete(collection)
        for artifact in artifacts:
            self.artifacts.delete(artifact, kind=KIND)

    # ------------------------------------------------------------------------------------------- the gathering
    def _window(self, request: DiagnosticsRequest) -> tuple[datetime, datetime]:
        cfg = self.config.diagnostics
        reference = _aware(request.reference_time) or self._now()
        minutes = {"last_5_minutes": 5, "last_15_minutes": 15, "last_30_minutes": 30}.get(request.window)
        if minutes is not None:
            return reference - timedelta(minutes=minutes), reference
        start, end = _aware(request.window_from), _aware(request.window_to)
        assert start is not None and end is not None
        if end - start > timedelta(minutes=cfg.max_window_minutes):
            raise UserError(
                f"a window may be at most {cfg.max_window_minutes} minutes (feedback.diagnostics.max_window_minutes)"
            )
        return start, end

    def _gather(self, actor: Actor, request: DiagnosticsRequest) -> tuple[list[Gathered], Context]:
        start, end = self._window(request)
        context = Context(actor=actor, request=request, start=start, end=end, is_operator=actor.is_staff)
        wanted = list(dict.fromkeys(request.categories))
        out: list[Gathered] = []
        handlers: dict[str, Callable[[Context], list[Gathered]]] = {
            "environment": self._environment,
            "application_logs": lambda c: self._logs(c, "application_logs", "api"),
            "backend_logs": lambda c: self._logs(c, "backend_logs", "worker"),
            "errors": self._errors,
            "trace": self._trace,
            "run_metadata": self._run_metadata,
            "test_summary": self._test_summary,
            "browser": self._browser,
            "screenshot": self._screenshot,
        }
        for category in wanted:
            try:
                out.extend(handlers[category](context))
            except Unavailable as why:
                out.append(self._missing(category, "unavailable", str(why), context))
            except Exception as exc:  # noqa: BLE001 - one source failing must not stop the others
                out.append(self._missing(category, "failed", f"it could not be read: {type(exc).__name__}", context))
        return out, context

    @staticmethod
    def _missing(category: str, outcome: str, detail: str, context: Context) -> Gathered:
        return Gathered(
            category=category,
            path=PATHS.get(category, f"{category}/missing"),
            source="",
            media_type="text/plain",
            outcome=outcome,
            detail=detail,
            time_from=context.start,
            time_to=context.end,
        )

    # --------------------------------------------------------------------------------------- one text, masked
    def _item(
        self,
        context: Context,
        category: str,
        path: str,
        source: str,
        *,
        text: str | None = None,
        value: Any = None,
        media_type: str = "text/plain",
        keep: str = "head",
        window: bool = True,
    ) -> Gathered:
        """Mask one piece of text (or one JSON value), cut it to the size limit, and say what was done."""
        limit = self.config.diagnostics.max_item_kb * 1024
        truncated = False
        if value is not None:
            result = self.redactor.redact_value(value)
            body = json.dumps(result.value, indent=2, ensure_ascii=False)
        else:
            assert text is not None
            result = self.redactor.redact_text(text)
            body = result.text
        data = body.encode("utf-8")
        if len(data) > limit:
            truncated = True
            data = data[-limit:] if keep == "tail" else data[:limit]
            body = data.decode("utf-8", errors="ignore")
            data = body.encode("utf-8")
        return Gathered(
            category=category,
            path=path,
            source=source,
            media_type=media_type,
            result=result,
            time_from=context.start if window else None,
            time_to=context.end if window else None,
            truncated=truncated,
            data=data,
        )

    # --------------------------------------------------------------------------------------------- the sources
    def _environment(self, context: Context) -> list[Gathered]:
        cfg = self.app
        facts = {
            "agentlab_version": __version__,
            "build": os.environ.get("AGENTLAB_BUILD") or "unknown",
            "python": platform.python_version(),
            "platform": platform.system() + " " + platform.machine(),
            "database": self.db.engine.dialect.name,
            "deployment": {
                "queue_backend": cfg.queue.backend,
                "artifact_store": cfg.storage.artifact_store,
                "browser_enabled": cfg.browser.enabled,
                "sandbox_provider": cfg.security.sandbox.provider,
                "accounts_registration": cfg.accounts.registration,
                "log_capture": cfg.feedback.diagnostics.capture_logs,
            },
            "collected_at": self._now().isoformat(),
            "note": "The server's host name, addresses, paths and environment variables are never included.",
        }
        return [
            self._item(
                context,
                "environment",
                PATHS["environment"],
                "AgentLab",
                value=facts,
                media_type="application/json",
                window=False,
            )
        ]

    def _logs(self, context: Context, category: str, process: str) -> list[Gathered]:
        """The lines of this process that belong to the caller: the run's own for a maintainer, the caller's own requests,
        and system-level warnings. Never another person's requests because they happened in the same minutes."""
        if not self.config.diagnostics.capture_logs:
            raise Unavailable("log capture is switched off on this server (feedback.diagnostics.capture_logs)")
        L = orm.LogEventRow
        key = str(context.actor.user_id or context.actor.kind)
        run_id = context.request.run_id if context.is_operator else None
        with self.db.session() as s:
            mine = select(L.request_id).where(
                L.principal == key, L.request_id.is_not(None), L.ts >= context.start, L.ts <= context.end
            )
            scopes: list[ColumnElement[bool]] = [
                and_(L.run_id.is_(None), L.request_id.is_(None), L.principal == ""),  # system level: no person, no run
                L.request_id.in_(mine),  # everything that happened during the caller's own failed or slow requests
            ]
            if run_id:
                scopes.append(L.run_id == run_id)
            rows = list(
                s.scalars(
                    select(L)
                    .where(L.process == process, L.ts >= context.start, L.ts <= context.end, or_(*scopes))
                    .order_by(L.ts.desc(), L.id.desc())
                    .limit(LOG_ROWS)
                )
            )
        if not rows:
            where = "worker" if process == "worker" else "server"
            raise Unavailable(f"the {where} logged nothing that concerns you in this period")
        rows.reverse()
        lines: list[str] = []
        for r in rows:
            stamp = _aware(r.ts)
            assert stamp is not None
            tag = f" [req {r.request_id}]" if r.request_id else (f" [run {r.run_id}]" if r.run_id else "")
            lines.append(f"{stamp:%Y-%m-%dT%H:%M:%S}Z {r.level:<7} {r.logger}{tag} {r.message}")
            if r.exception:
                lines.extend("    " + part for part in r.exception.splitlines())
        source = "log capture, " + ("web server" if process == "api" else "background worker")
        item = self._item(context, category, PATHS[category], source, text="\n".join(lines) + "\n", keep="tail")
        if len(rows) == LOG_ROWS:
            item.truncated = True
            context.notes.append(f"{category}: only the newest {LOG_ROWS} lines of the period are shown")
        return [item]

    def _run_for(self, context: Context) -> dict[str, Any]:
        if not context.is_operator:
            raise Unavailable("evaluation data is available to maintainers only")
        if not context.request.run_id:
            raise Unavailable("no run was named")
        try:
            return self.store.get_run(self.store.resolve_run_id(context.request.run_id))
        except (NotFoundError, UserError) as exc:
            raise Unavailable("that run does not exist on this server") from exc

    def _run_metadata(self, context: Context) -> list[Gathered]:
        run = self._run_for(context)
        totals = {k: v for k, v in (run.get("totals") or {}).items() if k != "queued_kind"}
        summary = {
            "run_id": run["id"],
            "status": run.get("status"),
            "suite": run.get("mode"),
            "created_at": run.get("created_at"),
            "started_at": run.get("started_at"),
            "finished_at": run.get("finished_at"),
            "error": run.get("error"),
            "totals": totals,
        }
        return [
            self._item(
                context,
                "run_metadata",
                PATHS["run_metadata"],
                f"run {run['id']}",
                value=summary,
                media_type="application/json",
                window=False,
            )
        ]

    def _result_for(self, context: Context, run_id: str) -> Any:
        test = context.request.test_id
        if not test:
            raise Unavailable("no test was named")
        for result in self.store.list_results(run_id):
            if result.test_id == test or str(getattr(result, "id", "")) == test:
                return result
        raise Unavailable("that test has no result in this run")

    def _test_summary(self, context: Context) -> list[Gathered]:
        run = self._run_for(context)
        result = self._result_for(context, run["id"])
        attempts = []
        for a in result.attempts:
            attempts.append(
                {
                    "attempt": a.attempt,
                    "status": a.status.value,
                    "latency_ms": a.latency_ms,
                    "error": a.error,
                    "error_kind": a.error_kind.value if a.error_kind else None,
                    "failed_checks": [{"type": x.type, "message": x.message} for x in a.assertions if not x.passed],
                    "outputs": [o[:500] for o in a.outputs[:6]],
                }
            )
        summary = {
            "test_id": result.test_id,
            "name": result.test_name,
            "category": result.category,
            "status": result.status.value,
            "severity": result.severity.value if result.severity else None,
            "blocked_reason": result.blocked_reason,
            "attempts": attempts,
        }
        return [
            self._item(
                context,
                "test_summary",
                PATHS["test_summary"],
                f"run {run['id']}, test {result.test_id}",
                value=summary,
                media_type="application/json",
                window=False,
            )
        ]

    def _errors(self, context: Context) -> list[Gathered]:
        parts: list[str] = []
        if context.is_operator and context.request.run_id:
            run = self._run_for(context)
            if run.get("error"):
                parts.append(f"run {run['id']}: {run['error']}")
            for result in self.store.list_results(run["id"]):
                if context.request.test_id and result.test_id != context.request.test_id:
                    continue
                for a in result.attempts:
                    if a.error:
                        kind = a.error_kind.value if a.error_kind else "error"
                        parts.append(f"test {result.test_id} attempt {a.attempt} ({kind}): {a.error}")
        L = orm.LogEventRow
        key = str(context.actor.user_id or context.actor.kind)
        run_id = context.request.run_id if context.is_operator else None
        with self.db.session() as s:
            mine = select(L.request_id).where(
                L.principal == key, L.request_id.is_not(None), L.ts >= context.start, L.ts <= context.end
            )
            scopes: list[ColumnElement[bool]] = [L.request_id.in_(mine)]
            if run_id:
                scopes.append(L.run_id == run_id)
            rows = s.scalars(
                select(L)
                .where(L.exception.is_not(None), L.ts >= context.start, L.ts <= context.end, or_(*scopes))
                .order_by(L.ts)
                .limit(200)
            )
            for r in rows:
                stamp = _aware(r.ts)
                parts.append(f"{stamp:%Y-%m-%dT%H:%M:%S}Z {r.logger}: {r.message}\n{r.exception}")
        if not parts:
            raise Unavailable("no error was recorded for this run, or for your requests in this period")
        return [self._item(context, "errors", PATHS["errors"], "recorded errors", text="\n\n".join(parts) + "\n")]

    def _trace(self, context: Context) -> list[Gathered]:
        run = self._run_for(context)
        request = context.request
        traces = self.store.list_traces(run["id"])
        wanted = [
            t
            for t in traces
            if (request.trace_id and t["id"] == request.trace_id)
            or (not request.trace_id and request.test_id and t.get("test_key") == request.test_id)
        ]
        if not wanted:
            raise Unavailable("no trace was recorded for that test or trace id")
        chosen = max(wanted, key=lambda t: t.get("attempt", 0))
        if not chosen.get("artifact_id"):
            raise Unavailable("the trace was not kept")
        try:
            document = self.artifacts.get_json(chosen["artifact_id"])
        except InfrastructureError as exc:
            raise Unavailable("the stored trace is no longer available") from exc
        return [
            self._item(
                context,
                "trace",
                PATHS["trace"],
                f"trace {chosen['id']}",
                value=document,
                media_type="application/json",
                window=False,
            )
        ]

    def _browser(self, context: Context) -> list[Gathered]:
        sent = context.request.browser
        if sent is None or not (sent.console or sent.network):
            raise Unavailable("the browser reported nothing: no console errors and no failed requests were seen")
        cap = self.config.diagnostics.max_browser_entries
        out: list[Gathered] = []
        if sent.console:
            entries = [e.model_dump(mode="json") for e in sent.console[-cap:]]
            out.append(
                self._item(
                    context,
                    "browser",
                    PATHS["browser:console"],
                    "web interface",
                    value=entries,
                    media_type="application/json",
                    window=False,
                )
            )
        if sent.network:
            entries = [e.model_dump(mode="json") for e in sent.network[-cap:]]
            out.append(
                self._item(
                    context,
                    "browser",
                    PATHS["browser:network"],
                    "web interface",
                    value=entries,
                    media_type="application/json",
                    window=False,
                )
            )
        return out

