"""Diagnostic information for an issue report: what AgentLab can really supply, collected only when asked for, masked before
anyone sees it, reviewed by the person, and attached only with their consent.

Only things the system actually keeps are offered, and each says why when it is not available. A source that fails does not
stop the others, and nothing is made up to fill a place in the bundle. Nothing leaves the server.

What it will *not* do is the important part: it never takes another person's activity because it happened at the same
time. A run's own log lines go to those who may see the run (maintainers); everyone else gets the lines of their own
requests and system-level warnings, and nothing else. The raw text is never stored: every item is masked first, and what is
kept is the masked text, in the restricted artifact store.
"""

