    def _screenshot(context: Context) -> list[Gathered]:
        raise Unavailable("AgentLab cannot capture a screenshot: attach one to your report as a file")

    # ------------------------------------------------------------------------------------------- presenting
    @staticmethod
    def _summary(status: str, report: dict[str, Any]) -> RedactionSummary:
        counts = dict(report.get("counts", {}))
        locations = [
            f"{f['kind']} at {f['location']}"
            for f in [*report.get("redactions", []), *report.get("second_inspection", [])][:LOCATIONS_SHOWN]
        ]
        return RedactionSummary(
            status=status,  # type: ignore[arg-type]
            counts=counts,
            locations=locations,
            external_sharing_blocked=status == "needs_review",
        )

    def _present(
        self,
        row: orm.DiagnosticCollectionRow | None,
        status: str,
        gathered: list[Gathered],
        context: Context,
        *,
        items: list[orm.DiagnosticItemRow] | None,
    ) -> DiagnosticCollectionOut:
        out: list[DiagnosticItemOut] = []
        warnings = list(context.notes)
        for index, item in enumerate(gathered):
            report = item.result.report() if item.result else {}
            status_text = item.result.status if item.result else "clean"
            preview = (
                item.data.decode("utf-8", errors="replace")[:PREVIEW_CHARS] if item.outcome == "collected" else None
            )
            out.append(
                DiagnosticItemOut(
                    id=items[index].id if items else f"preview-{index}",
                    category=item.category,
                    path=item.path,
                    source=item.source,
                    outcome=item.outcome,  # type: ignore[arg-type]
                    detail=item.detail,
                    time_from=item.time_from,
                    time_to=item.time_to,
                    size=len(item.data),
                    truncated=item.truncated,
                    included=item.outcome == "collected",
                    redaction=self._summary(status_text, report),
                    preview=preview,
                )
            )
            if item.outcome != "collected":
                label = LABELS.get(item.category, (item.category, ""))[0]
                warnings.append(f"{label} could not be included: {item.detail}")
            elif status_text == "needs_review":
                warnings.append(f"{item.path} needs review before it is shared outside AgentLab.")
        any_review = any(o.redaction.status == "needs_review" and o.outcome == "collected" for o in out)
        return DiagnosticCollectionOut(
            id=row.id if row else None,
            status=status,  # type: ignore[arg-type]
            created_at=_aware(row.created_at) if row else None,
            expires_at=_aware(row.expires_at) if row else None,
            window_from=context.start,
            window_to=context.end,
            items=out,
            warnings=warnings,
            total_bytes=sum(o.size for o in out if o.included),
            any_needs_review=any_review,
            submission_id=row.submission_id if row else None,
            consent_at=_aware(row.consent_at) if row else None,
        )

    def _load(
        self, actor: Actor, collection_id: str
    ) -> tuple[orm.DiagnosticCollectionRow, list[orm.DiagnosticItemRow]]:
        """A collection the actor may use: their own draft, or one attached to a submission they may see."""
        C, Itm = orm.DiagnosticCollectionRow, orm.DiagnosticItemRow
        with self.db.session() as s:
            row = s.get(C, collection_id.strip())
            if row is None or row.status == "expired":
                raise NotFoundError("no such collection")
            mine = (
                row.owner_user_id == actor.user_id
                if actor.user_id is not None
                else row.owner_user_id is None and row.owner_label == actor.label
            )
            if not mine:
                if row.submission_id is None or not actor.is_staff:
                    raise NotFoundError("no such collection")
                found, _hidden = self.submissions._find(s, actor, row.submission_id)
                if found is None:
                    raise NotFoundError("no such collection")
            items = list(s.scalars(select(Itm).where(Itm.collection_id == row.id).order_by(Itm.created_at, Itm.id)))
            s.expunge_all()
            return row, items

    def get(self, actor: Actor, collection_id: str) -> DiagnosticCollectionOut:
        row, items = self._load(actor, collection_id)
        out = []
        warnings: list[str] = []
        for i in items:
            text = None
            if i.artifact_id and i.included:
                try:
                    text = self.artifacts.get(i.artifact_id).decode("utf-8", errors="replace")[:PREVIEW_CHARS]
                except InfrastructureError:
                    text = None
            out.append(
                DiagnosticItemOut(
                    id=i.id,
                    category=i.category,
                    path=i.path,
                    source=i.source,
                    outcome=i.outcome if i.included or i.outcome != "collected" else "excluded",  # type: ignore[arg-type]
                    detail=i.detail,
                    time_from=_aware(i.time_from),
                    time_to=_aware(i.time_to),
                    size=i.size,
                    truncated=i.truncated,
                    included=i.included,
                    redaction=self._summary(i.redaction_status, i.redaction_report or {}),
                    preview=text,
                )
            )
            if i.outcome != "collected":
                warnings.append(f"{LABELS.get(i.category, (i.category, ''))[0]}: {i.detail}")
        return DiagnosticCollectionOut(
            id=row.id,
            status=row.status,  # type: ignore[arg-type]
            created_at=_aware(row.created_at),
            expires_at=_aware(row.expires_at),
            window_from=_aware(row.window_from),
            window_to=_aware(row.window_to),
            items=out,
            warnings=warnings,
            total_bytes=sum(o.size for o in out if o.included),
            any_needs_review=any(o.redaction.status == "needs_review" and o.included for o in out),
            submission_id=row.submission_id,
            consent_at=_aware(row.consent_at),
        )

    # ============================================================================================ attaching
    def attach(
        self, actor: Actor, ident: str, data: AttachDiagnosticsIn, *, client: str = ""
    ) -> DiagnosticCollectionOut:
        """Attach a draft to a submission, with consent. Items the person left out are deleted, not kept."""
        if data.consent is not True:
            raise UserError("explicit consent is required to attach diagnostics: " + CONSENT_TEXT)
        C, Itm = orm.DiagnosticCollectionRow, orm.DiagnosticItemRow
        discarded: list[str] = []
        with self.submissions.visible_submission(actor, ident, client=client) as (s, sub):
            row = s.get(C, data.collection_id.strip())
            owns = row is not None and (
                row.owner_user_id == actor.user_id
                if actor.user_id is not None
                else row.owner_user_id is None and row.owner_label == actor.label
            )
            if row is None or not owns or row.status != "draft":
                raise NotFoundError("no such collection to attach (it may have expired)")
            expires = _aware(row.expires_at)
            if expires is not None and expires < self._now():
                raise NotFoundError("no such collection to attach (it expired)")
            items = list(s.scalars(select(Itm).where(Itm.collection_id == row.id)))
            wanted = (
                set(data.include) if data.include is not None else {i.id for i in items if i.outcome == "collected"}
            )
            unknown = wanted - {i.id for i in items}
            if unknown:
                raise UserError("`include` names an item that is not in the collection")
            kept = 0
            for item in items:
                if item.outcome != "collected":
                    continue
                if item.id in wanted:
                    item.included = True
                    kept += 1
                else:
                    item.included = False
                    item.outcome = "collected"
                    if item.artifact_id:
                        discarded.append(item.artifact_id)
                        item.artifact_id = None
                    item.detail = "left out by the person who collected it"
                    item.size = 0
            if kept == 0:
                raise UserError("nothing is included: choose at least one item to attach")
            now = self._now()
            row.submission_id = sub.id
            row.status = "attached"
            row.expires_at = None
            row.consent_at = now
            row.consent_by = actor.stored_label[:80]
            sub.last_activity_at = now
            self.submissions.audit(
                s,
                "diagnostics_attached",
                actor,
                sub.id,
                client=client,
                number=sub.human_id,
                collection=row.id,
                items=kept,
                left_out=len(discarded),
                needs_review=sum(1 for i in items if i.included and i.redaction_status == "needs_review"),
            )
            s.flush()
        for artifact in discarded:
            self.artifacts.delete(artifact, kind=KIND)
        return self.get(actor, data.collection_id)

    def of_submission(self, actor: Actor, ident: str, *, client: str = "") -> list[DiagnosticCollectionOut]:
        C = orm.DiagnosticCollectionRow
        with self.submissions.visible_submission(actor, ident, client=client) as (s, sub):
            ids = list(s.scalars(select(C.id).where(C.submission_id == sub.id).order_by(C.created_at)))
        return [self.get(actor, i) for i in ids]

    # ============================================================================================ the bundle
    def bundle(self, actor: Actor, collection_id: str, *, client: str = "") -> tuple[bytes, str]:
        """The attached items as a ZIP: the files named in the specification, a manifest of what is and is not in it, and a
        README. Only items that were collected and included are files; nothing stands in for what was not."""
        row, items = self._load(actor, collection_id)
        included = [i for i in items if i.included and i.outcome == "collected" and i.artifact_id]
        if not included:
            raise NotFoundError("this collection has nothing to download")
        files: dict[str, bytes] = {}
        listing: list[dict[str, Any]] = []
        for i in items:
            entry: dict[str, Any] = {
                "path": i.path,
                "category": i.category,
                "source": i.source,
                "outcome": "collected" if i in included else ("excluded" if i.outcome == "collected" else i.outcome),
                "detail": i.detail,
                "time_from": _iso(i.time_from),
                "time_to": _iso(i.time_to),
                "truncated": bool(i.truncated),
                "redaction": {
                    "status": i.redaction_status,
                    "counts": (i.redaction_report or {}).get("counts", {}),
                    "external_sharing_blocked": i.redaction_status == "needs_review",
                },
                "generated": True,
            }
            if i in included:
                try:
                    data = self.artifacts.get(str(i.artifact_id))
                except InfrastructureError:
                    entry["outcome"] = "failed"
                    entry["detail"] = "the stored copy is no longer available"
                else:
                    files[f"diagnostics/{i.path}"] = data
                    entry["size"] = len(data)
                    entry["sha256"] = hashlib.sha256(data).hexdigest()
            listing.append(entry)
        manifest = {
            "generated": True,
            "generator": f"AgentLab {__version__}",
            "generated_at": self._now().isoformat(),
            "collection": row.id,
            "submission": row.submission_id,
            "window": {
                "from": _iso(row.window_from),
                "to": _iso(row.window_to),
            },
            "consent": {
                "given_at": _iso(row.consent_at),
                "by": row.consent_by,
            },
            "items": listing,
            "external_sharing_blocked": any(
                e["redaction"]["external_sharing_blocked"] for e in listing if e["outcome"] == "collected"
            ),
            "note": "Redaction reduces risk; it does not guarantee that nothing sensitive remains.",
        }
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
            archive.writestr("diagnostics/manifest.json", json.dumps(manifest, indent=2, ensure_ascii=False))
            archive.writestr("diagnostics/README.txt", README)
            for path, data in sorted(files.items()):
                archive.writestr(path, data)
        if row.submission_id:
            with self.submissions.visible_submission(actor, row.submission_id, client=client) as (s, sub):
                self.submissions.audit(
                    s, "diagnostics_downloaded", actor, sub.id, client=client, number=sub.human_id, collection=row.id
                )
        return buffer.getvalue(), f"diagnostics-{row.id[:8]}.zip"

    # ======================================================================================== redaction preview
