import { useState } from "react";
import { describeError } from "../../api/errors";
import type { Attachment, Handoff, SubmissionDetail } from "../../api/types";
import { useAsync } from "../../hooks/useAsync";
import { formatBytes } from "../../lib/feedback";
import { formatTime } from "../../lib/format";
import { useSession } from "../../session";
import { Checkbox } from "../controls";
import { Badge, CopyButton, Notice, saveBlob, useToast } from "../ui";

type Choice = "default" | "exclude" | "original";

/** Whether a file can be put in as a masked or checked copy by itself, so that "as uploaded" is not a choice for it. */
function handledByDefault(a: Attachment): boolean {
  return a.text_like && (a.sanitized_available || a.secrets.status === "none");
}

/** What a package would hold (or does): the files with their hashes, what was left out and why, the warnings, and the task. */
export function EngineeringHandoffPreview({ handoff }: { handoff: Handoff }) {
  return (
    <div className="stack">
      {handoff.warnings.length > 0 && (
        <Notice tone="warn" title="Read before you use this package">
          <ul style={{ margin: 0, paddingLeft: 20 }}>
            {handoff.warnings.map((w) => (
              <li key={w}>{w}</li>
            ))}
          </ul>
        </Notice>
      )}
      {handoff.external_sharing_blocked && (
        <Notice tone="warn" title="Not to be shared outside AgentLab yet">
          Something in it still needs a person&apos;s review. Masking reduces risk; it does not guarantee that nothing sensitive remains.
        </Notice>
      )}
      <div>
        <h4 style={{ margin: "0 0 6px" }}>
          Files ({handoff.files.length}){" "}
          {handoff.includes_unsanitized && <Badge tone="warn">holds files as uploaded</Badge>}
        </h4>
        <div className="table-wrap">
          <table className="table">
            <caption className="sr-only">Files in the package</caption>
            <thead>
              <tr>
                <th scope="col">File</th>
                <th scope="col">What it is</th>
                <th scope="col">Made from</th>
                <th scope="col" className="num">
                  Size
                </th>
                <th scope="col">SHA-256</th>
              </tr>
            </thead>
            <tbody>
              {handoff.files.map((f) => (
                <tr key={f.path}>
                  <td className="mono">{f.path}</td>
                  <td>
                    {f.kind === "generated" && "Generated by AgentLab"}
                    {f.kind === "diagnostic" && "Collected, masked"}
                    {f.kind === "sanitized_copy" && "Reporter's file, masked copy"}
                    {f.kind === "original_evidence" && (f.note.includes("UNSANITIZED") ? "Reporter's file, as uploaded (unsanitized)" : "Reporter's file, as uploaded")}
                    {f.note && f.kind !== "generated" && <div className="muted small">{f.note}</div>}
                  </td>
                  <td className="muted small">{f.source}</td>
                  <td className="num">{formatBytes(f.size)}</td>
                  <td className="mono small" title={f.sha256}>
                    {f.sha256.slice(0, 12)}…
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
      {handoff.left_out.length > 0 && (
        <div>
          <h4 style={{ margin: "0 0 6px" }}>Left out ({handoff.left_out.length})</h4>
          <ul style={{ margin: 0, paddingLeft: 20 }}>
            {handoff.left_out.map((x) => (
              <li key={x.what}>
                <strong>{x.what}</strong>: {x.reason}
              </li>
            ))}
          </ul>
        </div>
      )}
      <details>
        <summary>The task file, as Claude Code will read it</summary>
        <div className="row" style={{ margin: "8px 0" }}>
          <CopyButton text={handoff.task} label="Copy the task" />
        </div>
        <pre className="codebox" style={{ whiteSpace: "pre-wrap", maxHeight: 420, overflow: "auto" }}>
          {handoff.task}
        </pre>
      </details>
    </div>
  );
}

/** A package that was built: who, when, what it reflects, and the two ways to take it. Every download is recorded. */
export function EngineeringHandoffDownload({ handoff }: { handoff: Handoff }) {
  const { api } = useSession();
  const toast = useToast();
  const [busy, setBusy] = useState(false);
  const take = async (what: "package" | "task") => {
    if (!handoff.id) return;
    setBusy(true);
    try {
      const file = what === "package" ? await api.handoffPackage(handoff.id) : await api.handoffTask(handoff.id);
      saveBlob(file.blob, file.name ?? (what === "package" ? `agentlab-handoff-${handoff.number}.zip` : "CLAUDE_CODE_TASK.md"));
    } catch (e) {
      toast.push("error", describeError(e));
    } finally {
      setBusy(false);
    }
  };
  return (
    <div className="row between" style={{ flexWrap: "wrap", gap: 8 }}>
      <div>
        Built {formatTime(handoff.created_at)} by {handoff.created_by}, for version {handoff.submission_version}
        <span className="muted small">
          {" "}
          · {handoff.files.length} files · {formatBytes(handoff.size)} · SHA-256 <span className="mono">{handoff.sha256?.slice(0, 12)}…</span>
        </span>{" "}
        {handoff.external_sharing_blocked && <Badge tone="warn">needs review</Badge>}{" "}
        {handoff.includes_unsanitized && <Badge tone="warn">unsanitized files</Badge>}
      </div>
      <div className="row">
        <button type="button" className="btn small" disabled={busy} onClick={() => void take("package")}>
          Download the package (ZIP)
        </button>
        <button type="button" className="btn small" disabled={busy} onClick={() => void take("task")}>
          Download CLAUDE_CODE_TASK.md
        </button>
      </div>
    </div>
  );
}

/** Choose what goes into a package, look at it, build it, take it. Nothing here runs Claude Code or sends the package. */
export function EngineeringHandoff({ submission, attachments }: { submission: SubmissionDetail; attachments: Attachment[] }) {
  const { api } = useSession();
  const built = useAsync((signal) => api.handoffs(submission.id, signal), [api, submission.id]);
  const [includeNotes, setIncludeNotes] = useState(false);
  const [includeDiagnostics, setIncludeDiagnostics] = useState(true);
  const [choices, setChoices] = useState<Record<string, Choice>>({});
  const [preview, setPreview] = useState<Handoff | null>(null);
  const [viewing, setViewing] = useState<string | null>(null);
  const [busy, setBusy] = useState<"preview" | "build" | null>(null);
  const [error, setError] = useState<string | null>(null);

  const request = () => ({
    include_internal_notes: includeNotes,
    include_diagnostics: includeDiagnostics,
    exclude_attachments: Object.entries(choices)
      .filter(([, c]) => c === "exclude")
      .map(([id]) => id),
    include_originals: Object.entries(choices)
      .filter(([, c]) => c === "original")
      .map(([id]) => id),
  });

  const run = async (what: "preview" | "build") => {
    setBusy(what);
    setError(null);
    try {
      if (what === "preview") {
        setPreview(await api.previewHandoff(submission.id, request()));
      } else {
        await api.createHandoff(submission.id, request());
        setPreview(null);
        built.reload();
      }
    } catch (e) {
      setError(describeError(e));
    } finally {
      setBusy(null);
    }
  };

  const open = built.data?.find((h) => h.id === viewing) ?? null;
  return (
    <div className="stack">
      <p className="muted" style={{ margin: 0 }}>
        Builds a sanitized package (a ZIP, and CLAUDE_CODE_TASK.md on its own) for an authorised engineer to take. Nothing here runs
        Claude Code, changes the repository or sends the package anywhere. What a person wrote is quoted as evidence and not obeyed.
      </p>
      <fieldset className="stack tight" style={{ border: 0, padding: 0, margin: 0 }}>
        <legend className="sr-only">What goes in</legend>
        <Checkbox checked={includeDiagnostics} onChange={setIncludeDiagnostics}>
          The diagnostic information the reporter attached (masked)
        </Checkbox>
        <Checkbox checked={includeNotes} onChange={setIncludeNotes}>
          Internal notes and internal files (for the maintainers&apos; team only: remove them before sharing further)
        </Checkbox>
      </fieldset>
      {attachments.length > 0 && (
        <div className="table-wrap">
          <table className="table">
            <caption className="sr-only">Attachments and what the package does with each</caption>
            <thead>
              <tr>
                <th scope="col">Attachment</th>
                <th scope="col">By default</th>
                <th scope="col">In this package</th>
              </tr>
            </thead>
            <tbody>
              {attachments.map((a) => {
                const own = handledByDefault(a);
                return (
                  <tr key={a.id}>
                    <td>
                      <span className="mono">{a.name}</span> <span className="muted small">{a.type}, {formatBytes(a.size)}</span>
                    </td>
                    <td className="small">
                      {a.text_like && a.sanitized_available && "Put in as its masked copy"}
                      {a.text_like && !a.sanitized_available && a.secrets.status === "none" && "Put in (no secrets recognised)"}
                      {a.text_like && !a.sanitized_available && a.secrets.status === "not_inspected" && "Left out: too large to check for secrets"}
                      {!a.text_like && "Left out: it cannot be masked (an image, a document or an archive)"}
                    </td>
                    <td>
                      <label className="sr-only" htmlFor={`h-${a.id}`}>
                        What to do with {a.name}
                      </label>
                      <select
                        id={`h-${a.id}`}
                        className="select"
                        value={choices[a.id] ?? "default"}
                        onChange={(e) => setChoices((c) => ({ ...c, [a.id]: e.target.value as Choice }))}
                      >
                        <option value="default">As described</option>
                        <option value="exclude">Leave out</option>
                        {!own && <option value="original">Put in as uploaded (unsanitized)</option>}
                      </select>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      )}
      {Object.values(choices).includes("original") && (
        <Notice tone="warn" title="You chose to put a file in as it was uploaded">
          Nothing was masked in it, and it can show anything. The package says so, and the audit trail records that you built it.
        </Notice>
      )}
      {error && <Notice tone="error">{error}</Notice>}
      <div className="row">
        <button type="button" className="btn" disabled={busy !== null} onClick={() => void run("preview")}>
          {busy === "preview" ? "Preparing…" : "Preview the package"}
        </button>
        <button type="button" className="btn primary" disabled={busy !== null} onClick={() => void run("build")}>
          {busy === "build" ? "Building…" : "Build the package"}
        </button>
      </div>
      {preview && (
        <div className="stack">
          <h3 style={{ margin: 0, fontSize: 14 }}>Preview: nothing was built or kept</h3>
          <EngineeringHandoffPreview handoff={preview} />
        </div>
      )}
      <div className="stack">
        <h3 style={{ margin: 0, fontSize: 14 }}>Packages built from this submission</h3>
        {built.data && built.data.length === 0 && <p className="muted">None yet.</p>}
        {built.error && <Notice tone="error">{built.error}</Notice>}
        <ul className="stack tight" style={{ listStyle: "none", margin: 0, padding: 0 }}>
          {(built.data ?? []).map((h) => (
            <li key={h.id} className="list-item">
              <EngineeringHandoffDownload handoff={h} />
              <div style={{ marginTop: 6 }}>
                <button type="button" className="btn small ghost" aria-expanded={viewing === h.id} onClick={() => setViewing(viewing === h.id ? null : h.id)}>
                  {viewing === h.id ? "Hide what it holds" : "See what it holds"}
                </button>
              </div>
            </li>
          ))}
        </ul>
        {open && <EngineeringHandoffPreview handoff={open} />}
      </div>
    </div>
  );
}
